"""Persistent user preferences and localized assistant behavior."""

import os
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Dict, List
from local_ollama_agent import DEFAULT_MODEL, normalize_model_name


LANGUAGE_NAMES = {
    "en": "English",
    "tr": "Türkçe",
    "de": "Deutsch",
    "fr": "Français",
}


@dataclass
class AppSettings:
    model: str = DEFAULT_MODEL
    language: str = "tr"
    personality: str = ""
    user_name: str = ""
    personal_info: str = ""
    allowed_folders: List[str] = field(default_factory=list)

    @classmethod
    def load(cls, store) -> "AppSettings":
        defaults = cls(
            model=normalize_model_name(os.environ.get("OLLAMA_MODEL", DEFAULT_MODEL))
        )
        saved = store.get_preferences()
        settings = cls(
            model=str(saved.get("model") or defaults.model),
            language=str(saved.get("language") or defaults.language),
            personality=str(saved.get("personality") or ""),
            user_name=str(saved.get("user_name") or ""),
            personal_info=str(saved.get("personal_info") or ""),
            allowed_folders=[
                str(Path(path).expanduser().resolve())
                for path in saved.get("allowed_folders", [])
                if isinstance(path, str) and Path(path).expanduser().is_dir()
            ] if isinstance(saved.get("allowed_folders", []), list) else [],
        )
        if settings.language not in LANGUAGE_NAMES:
            settings.language = defaults.language
        return settings

    def save(self, store) -> None:
        self.model = normalize_model_name(self.model)
        if self.language not in LANGUAGE_NAMES:
            raise ValueError("Unsupported interface language.")
        if not isinstance(self.allowed_folders, list):
            raise ValueError("Allowed folders must be a list.")
        normalized = []
        for folder in self.allowed_folders:
            path = Path(folder).expanduser()
            if not path.is_dir():
                raise ValueError(f"Allowed folder does not exist: {folder}")
            resolved = str(path.resolve())
            if resolved not in normalized:
                normalized.append(resolved)
        self.allowed_folders = normalized
        store.save_preferences(asdict(self))

    def system_prompt(self, tools_available: bool = False) -> str:
        language = LANGUAGE_NAMES[self.language]
        if self.language == "tr":
            prompt = (
                f"Sen Ollama üzerinden {self.model} modeliyle çalışan yerel bir asistansın. "
                f"Her zaman {language} dilinde yanıt ver. Sıcak, doğal, doğru ve yardımsever ol. "
                + (
                    "Dosya ve terminal araçları yalnızca ajan talimatlarında belirtildiği şekilde kullan. "
                    if tools_available
                    else "Bu sohbet arayüzünde dosya veya terminal araçların yoktur; bunları kullandığını "
                    "iddia etme. "
                )
                + "Bilmediğin bilgileri uydurma."
            )
        else:
            prompt = (
                f"You are a local assistant powered by the Ollama model {self.model}. "
                f"Always reply in {language}. Be warm, natural, accurate, and helpful. "
                + (
                    "Use file and terminal tools only as described in the agent instructions. "
                    if tools_available
                    else "This chat interface has no file or terminal tools; do not claim to use them. "
                )
                + "Do not invent facts you are unsure about."
            )
        if self.user_name.strip():
            prompt += f"\n\nThe user's name is {self.user_name.strip()}."
        if self.personal_info.strip():
            prompt += f"\nUseful information about the user: {self.personal_info.strip()}"
        if self.personality.strip():
            prompt += f"\n\nAssistant personality and style requested by the user:\n{self.personality.strip()}"
        return prompt


